#!/usr/bin/env python3
"""Regenerate src/data/SchemaSql.cpp from schema/schema.sql (run after any schema change)."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
sql = (root / "schema" / "schema.sql").read_text(encoding="utf-8")
assert ')SQL"' not in sql
out = ('// GENERATED by tools/gen_schema.py from schema/schema.sql - do not edit by hand.\n'
       '#include "data/Database.h"\n\nnamespace lms {\n\n'
       'const char* schemaSql() {\n    return R"SQL(' + sql + ')SQL";\n}\n\n} // namespace lms\n')
(root / "src" / "data" / "SchemaSql.cpp").write_text(out, encoding="utf-8")
print("wrote src/data/SchemaSql.cpp", len(sql), "bytes of SQL")
