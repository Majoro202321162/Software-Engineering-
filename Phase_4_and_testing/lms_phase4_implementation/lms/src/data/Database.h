// SQLite access helpers: Database, Statement and the RAII Transaction
// (Phase 3, Figure 3.6, DD-07). The only place that talks to SQLite directly.
#pragma once
#include <memory>
#include <optional>
#include <string>

struct sqlite3;
struct sqlite3_stmt;

namespace lms {

class Database;

// A prepared statement; values are always bound, never joined into SQL text (NFR-06).
class Statement {
public:
    Statement(Database& db, const std::string& sql);
    Statement(Statement&& other) noexcept;
    Statement& operator=(Statement&&) = delete;
    Statement(const Statement&) = delete;
    Statement& operator=(const Statement&) = delete;
    ~Statement();

    // Parameter indexes start at 1.
    void bind(int index, int v);
    void bind(int index, long long v);
    void bind(int index, double v);
    void bind(int index, bool v);
    void bind(int index, const std::string& v);
    void bind(int index, const char* v);
    void bindNull(int index);
    template <class T>
    void bind(int index, const std::optional<T>& v) {
        if (v) bind(index, *v); else bindNull(index);
    }

    bool step();                       // true while a row is available
    void reset();

    // Column indexes start at 0.
    bool isNull(int col) const;
    int columnInt(int col) const;
    long long columnInt64(int col) const;
    double columnDouble(int col) const;
    std::string columnText(int col) const;          // "" when NULL
    std::optional<std::string> columnOptText(int col) const;
    std::optional<int> columnOptInt(int col) const;

private:
    Database* db_;
    sqlite3_stmt* stmt_;
};

class Transaction;

class Database {
public:
    Database() = default;
    Database(const Database&) = delete;
    Database& operator=(const Database&) = delete;
    ~Database();

    // Opens the file (":memory:" for tests), switches foreign keys ON (NFR-09)
    // and creates the schema when the file is new.
    void open(const std::string& path);
    void close();
    Statement prepare(const std::string& sql) { return Statement(*this, sql); }
    void exec(const std::string& sql);
    long long lastInsertId() const;
    Transaction begin();
    // Consistent copy of the database file into targetFile (FR-34).
    void backupTo(const std::string& targetFile);

    sqlite3* handle() const { return handle_; }
    [[noreturn]] void throwError(const std::string& context) const;

private:
    friend class Transaction;
    void beginTx();
    void commitTx();
    void rollbackTx() noexcept;

    sqlite3* handle_ = nullptr;
    int txDepth_ = 0;
    bool txFailed_ = false;
};

// Commits only when commit() is called; the destructor rolls back otherwise, so an
// exception can never leave a half-saved mark. Nested use joins the outer transaction.
class Transaction {
public:
    explicit Transaction(Database& db);
    Transaction(Transaction&& other) noexcept;
    Transaction(const Transaction&) = delete;
    Transaction& operator=(const Transaction&) = delete;
    ~Transaction();
    void commit();
private:
    Database* db_;
    bool committed_ = false;
    bool active_ = true;
};

// Embedded copy of schema/schema.sql (generated by tools/gen_schema.py).
const char* schemaSql();

} // namespace lms
